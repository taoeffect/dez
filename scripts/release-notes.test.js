import { createServer } from 'node:net';
import { describe, expect, it } from 'vitest';
import { describeError, formatReleaseBody, keepNewestThatFit, nearestAncestorTag, readApiKey, readReleaseNotesReply } from './release-notes.js';

function reply(content, finishReason = 'stop') {
  return { choices: [{ finish_reason: finishReason, message: { content } }] };
}

describe('readReleaseNotesReply', () => {
  it('returns the notes of a complete reply without a code fence', () => {
    const notes = '**NEW**\n\n- Ability to add a custom provider';
    expect(readReleaseNotesReply(reply(`\`\`\`markdown\n${notes}\n\`\`\`\n`))).toBe(notes);
    expect(readReleaseNotesReply(reply(`\n${notes}\n`))).toBe(notes);
  });

  it('returns no notes when the model replies NONE', () => {
    expect(readReleaseNotesReply(reply('NONE\n'))).toBe('');
  });

  it('fails on a reply cut off at the token limit, even with empty content', () => {
    expect(() => readReleaseNotesReply(reply('', 'length'))).toThrow(/token limit/);
    expect(() => readReleaseNotesReply(reply('**NEW**\n\n- Half a', 'length'))).toThrow(/token limit/);
  });

  it('fails on a reply that ended early for another reason', () => {
    expect(() => readReleaseNotesReply(reply('NONE', 'sensitive'))).toThrow(/finish_reason: sensitive/);
    expect(() => readReleaseNotesReply(reply('NONE', null))).toThrow(/finish_reason: none/);
  });

  it('fails on an empty complete reply instead of treating it as no changes', () => {
    expect(() => readReleaseNotesReply(reply('  \n'))).toThrow(/empty reply/);
    expect(() => readReleaseNotesReply(reply(null))).toThrow(/no text content/);
  });

  it('fails on a reply with no choices', () => {
    expect(() => readReleaseNotesReply({ error: { message: 'busy' } })).toThrow(/no choices/);
    expect(() => readReleaseNotesReply({ choices: [] })).toThrow(/no choices/);
    expect(() => readReleaseNotesReply(null)).toThrow(/no choices/);
  });
});

describe('keepNewestThatFit', () => {
  const budget = { maxMessageChars: 10, maxTotalChars: 20, separatorChars: 2 };

  it('keeps the newest messages that fit and counts the older ones as omitted', () => {
    expect(keepNewestThatFit(['newest', 'middle', 'oldest'], budget))
      .toEqual({ kept: ['newest', 'middle'], omitted: 1 });
  });

  it('cuts a message longer than the per-message limit', () => {
    expect(keepNewestThatFit(['squash commit body', 'older one'], budget))
      .toEqual({ kept: ['squash com…'], omitted: 1 });
  });

  it('keeps every message when all fit', () => {
    expect(keepNewestThatFit(['a', 'b'], budget)).toEqual({ kept: ['a', 'b'], omitted: 0 });
  });
});

describe('formatReleaseBody', () => {
  const template = '# Desktop builds\n\nBuilds are attached.\n\n';

  it('puts the notes under Changes after the template and names the model', () => {
    expect(formatReleaseBody({ template, notes: '**FIXES**\n\n- A fix', model: 'glm-5.3' })).toBe(
      '# Desktop builds\n\nBuilds are attached.\n\n## Changes\n\n**FIXES**\n\n- A fix\n\n'
        + 'Release notes generated by glm-5.3.\n',
    );
  });

  it('is the template only when there are no notes', () => {
    expect(formatReleaseBody({ template, notes: '', model: 'glm-5.3' }))
      .toBe('# Desktop builds\n\nBuilds are attached.\n');
  });
});

describe('nearestAncestorTag', () => {
  // v0.7.0 <- v0.8.0 <- v0.9.0 <- v0.10.0, and v0.8.1 on an unmerged branch
  // off v0.8.0.
  const parents = { 'v0.8.0': 'v0.7.0', 'v0.8.1': 'v0.8.0', 'v0.9.0': 'v0.8.0', 'v0.10.0': 'v0.9.0' };
  function isAncestor(ancestor, tag) {
    for (let current = tag; current; current = parents[current]) {
      if (current === ancestor) return true;
    }
    return false;
  }

  it('picks the nearest ancestor, not the one listed first', () => {
    expect(nearestAncestorTag('v0.10.0', ['v0.7.0', 'v0.8.0', 'v0.9.0'], isAncestor)).toBe('v0.9.0');
    expect(nearestAncestorTag('v0.10.0', ['v0.9.0', 'v0.7.0', 'v0.8.0'], isAncestor)).toBe('v0.9.0');
  });

  it('skips the tag itself and tags that are not its ancestors', () => {
    expect(nearestAncestorTag('v0.10.0', ['v0.10.0', 'v0.8.1', 'v0.8.0'], isAncestor)).toBe('v0.8.0');
    expect(nearestAncestorTag('v0.8.1', ['v0.10.0', 'v0.9.0', 'v0.7.0', 'v0.8.0'], isAncestor)).toBe('v0.8.0');
  });

  it('returns undefined when no other tag is an ancestor', () => {
    expect(nearestAncestorTag('v0.7.0', ['v0.7.0', 'v0.8.0'], isAncestor)).toBeUndefined();
  });
});

describe('describeError', () => {
  it('shows the reason of a failed fetch, not only "fetch failed"', async () => {
    const server = createServer();
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const { port } = server.address();
    await new Promise(resolve => server.close(resolve));

    const error = await fetch(`http://127.0.0.1:${port}/`).catch(failure => failure);
    expect(describeError(error)).toBe(`fetch failed (connect ECONNREFUSED 127.0.0.1:${port})`);
  });

  it('shows each address of a cause with an empty message', () => {
    const cause = new AggregateError([
      new Error('connect ECONNREFUSED ::1:443'),
      new Error('connect ECONNREFUSED 127.0.0.1:443'),
    ], '');
    expect(describeError(new TypeError('fetch failed', { cause })))
      .toBe('fetch failed (connect ECONNREFUSED ::1:443; connect ECONNREFUSED 127.0.0.1:443)');
  });
});

describe('readApiKey', () => {
  // An error object makes toThrow compare the whole message, so the key
  // cannot be in it.
  it.each(['SEC\nRET', 'SEC\rRET', 'SEC\0RET'])('refuses %j without the key in the error', key => {
    expect(() => readApiKey({ ZAI_API_KEY: key }, 'zai-coding-plan'))
      .toThrow(new Error('ZAI_API_KEY holds a line break or NUL, so it is not a valid API key'));
  });

  it('removes line breaks at the ends, which a pasted key often has', () => {
    expect(readApiKey({ ZAI_API_KEY: '\nSECRET\r\n' }, 'zai-coding-plan')).toBe('SECRET');
  });

  it('refuses a key that is only whitespace', () => {
    expect(() => readApiKey({ ZAI_API_KEY: ' \n' }, 'zai-coding-plan'))
      .toThrow('ZAI_API_KEY (the API key for zai-coding-plan) is not set');
  });
});
