import { gunzipSync } from 'node:zlib';
import { describe, expect, it } from 'vitest';
import {
  crateLicenses,
  denoSourceLicenses,
  isLicenseFile,
  licenseTextsFile,
  lockedCrates,
  submodulesOf,
  tarFiles
} from './deno-licenses.js';
import { tarGzFile } from './testing.js';

describe('isLicenseFile', () => {
  it('takes the names that sources give their license texts, at any depth', () => {
    const paths = [
      'LICENSE', 'LICENSE-MIT', 'license-apache-2.0', 'LICENCE.md', 'LICENSE_1_0.txt', 'LICENSE.TXT', 'LICENSE.rst',
      'COPYING', 'COPYING.LGPLv2.1', 'COPYRIGHT.txt', 'UNLICENSE', 'NOTICE', 'PATENTS', 'THIRD-PARTY-LICENSES',
      'aws-lc/third_party/fiat/LICENSE', 'src/unicode/data/LICENSE-UNICODE'
    ];
    for (const path of paths) {
      expect(isLicenseFile(path), path).toBe(true);
    }
  });

  it('refuses code and data with such a name, and other files', () => {
    const paths = [
      'src/licenses.rs', 'src/compiler/turboshaft/copying-phase.cc', 'src/compiler/turboshaft/copying-phase.h',
      'tools/license-check.sh', 'license.html', 'lib/libwinapi_oemlicense.a', 'util/perl/copyright.pm',
      'crypto/x509/v3_usernotice.c', 'README.md', 'Cargo.toml', 'AUTHORS', 'src/lib.rs'
    ];
    for (const path of paths) {
      expect(isLicenseFile(path), path).toBe(false);
    }
  });

  it('refuses the files of the tests of a source, which are not a part of a program', () => {
    expect(isLicenseFile('tests/registry/npm/chalk/LICENSE')).toBe(false);
    expect(isLicenseFile('test/fixtures/LICENSE')).toBe(false);
    expect(isLicenseFile('vendor/zlib/Tests/COPYING')).toBe(false);
    // Only a folder with that name.
    expect(isLicenseFile('contest/LICENSE')).toBe(true);
    expect(isLicenseFile('testing/LICENSE')).toBe(true);
  });
});

describe('tarFiles', () => {
  const files = tar => Array.from(tarFiles(tar), file => [file.name, file.bytes.toString()]);
  const longName = `a-1.0.0/${'folder/'.repeat(20)}LICENSE-APACHE`;

  it('gives the name and the bytes of each regular file, and leaves the folders out', () => {
    const tar = gunzipSync(
      tarGzFile([
        { name: 'a-1.0.0/', type: '5' },
        { name: 'a-1.0.0/empty' },
        { name: 'a-1.0.0/one-block', text: 'x'.repeat(512) },
        { name: 'a-1.0.0/more', text: 'y'.repeat(513) },
        { name: 'a-1.0.0/link', type: '2' },
        { name: 'a-1.0.0/LICENSE', text: 'MIT' }
      ])
    );
    expect(files(tar)).toEqual([
      ['a-1.0.0/empty', ''],
      ['a-1.0.0/one-block', 'x'.repeat(512)],
      ['a-1.0.0/more', 'y'.repeat(513)],
      ['a-1.0.0/LICENSE', 'MIT']
    ]);
  });

  it('gives the whole name of a file with a long name, and the short name of the file after it', () => {
    const tar = gunzipSync(tarGzFile([{ name: longName, text: 'Apache' }, { name: 'a-1.0.0/LICENSE-MIT', text: 'MIT' }]));
    expect(files(tar)).toEqual([[longName, 'Apache'], ['a-1.0.0/LICENSE-MIT', 'MIT']]);
  });

  it('joins the prefix and the name of a POSIX header', () => {
    const tar = gunzipSync(tarGzFile([{ name: 'LICENSE', text: 'MIT' }]));
    // The POSIX magic and version in the place of the GNU magic, and the
    // folders of the file in the prefix field.
    tar.write('ustar\x0000', 257, 'latin1');
    tar.write('a-1.0.0/vendor', 345);
    expect(files(tar)).toEqual([['a-1.0.0/vendor/LICENSE', 'MIT']]);
  });

  it('refuses a tar file with a part missing', () => {
    const tar = gunzipSync(tarGzFile([{ name: 'a-1.0.0/LICENSE', text: 'x'.repeat(2000) }]));
    expect(() => files(tar.subarray(0, 1024))).toThrow('The tar file is damaged, or a part of it is missing.');
  });

  it('refuses pax headers, which can hold a name that this reader would not see', () => {
    const tar = gunzipSync(
      tarGzFile([{ name: 'PaxHeaders/LICENSE', text: `30 path=${longName}\n`, type: 'x' }, { name: 'a-1.0.0/LICENSE', text: 'MIT' }])
    );
    expect(() => files(tar)).toThrow('The tar file has pax headers, which this script does not read.');
  });
});

describe('lockedCrates', () => {
  const lock = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "anyhow"
version = "1.0.100"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "${'a'.repeat(64)}"

[[package]]
name = "deno"
version = "2.9.8"
dependencies = [
 "anyhow",
 "openssl-src 300.5.0+3.5.0 (registry+https://github.com/rust-lang/crates.io-index)",
]

[[package]]
name = "openssl-src"
version = "300.5.0+3.5.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "${'b'.repeat(64)}"
dependencies = [
 "cc",
]
`;

  it('gives each crate file of crates.io with its SHA-256, and not the packages of the workspace', () => {
    expect(lockedCrates(lock)).toEqual([
      { name: 'anyhow', version: '1.0.100', checksum: 'a'.repeat(64) },
      { name: 'openssl-src', version: '300.5.0+3.5.0', checksum: 'b'.repeat(64) }
    ]);
  });

  it('refuses a package from a source with no pinned crate file', () => {
    const git = `${lock}\n[[package]]\nname = "fork"\nversion = "0.1.0"\nsource = "git+https://example.com/fork#0123abc"\n`;
    expect(() => lockedCrates(git)).toThrow(/^Cargo\.lock names the package fork 0\.1\.0 from git\+https:\/\/example\.com\/fork#0123abc, /);
    const noChecksum = `${lock}\n[[package]]\nname = "bare"\nversion = "0.1.0"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n`;
    expect(() => lockedCrates(noChecksum)).toThrow(/^Cargo\.lock names the package bare 0\.1\.0 /);
  });
});

describe('crateLicenses', () => {
  const crate = { name: 'a', version: '1.0.0' };
  const manifest = license => `[package]\nname = "a"\nversion = "1.0.0"\n${license}\n\n[dependencies.b]\nversion = "1"\n`;

  it('gives the stated license and the license files of every folder, in the order of the paths', () => {
    const file = tarGzFile([
      { name: 'a-1.0.0/src/lib.rs', text: '// MIT License' },
      { name: 'a-1.0.0/vendor/zlib/LICENSE', text: 'zlib' },
      { name: 'a-1.0.0/LICENSE-MIT', text: 'MIT' },
      { name: 'a-1.0.0/Cargo.toml', text: manifest('license = "MIT OR Apache-2.0"') },
      { name: 'a-1.0.0/LICENSE-APACHE', text: 'Apache' }
    ]);
    expect(crateLicenses(crate, file)).toEqual({
      license: 'MIT OR Apache-2.0',
      files: [
        { path: 'LICENSE-APACHE', text: 'Apache' },
        { path: 'LICENSE-MIT', text: 'MIT' },
        { path: 'vendor/zlib/LICENSE', text: 'zlib' }
      ]
    });
  });

  it('gives a text with plain line ends and no space around it, so that equal texts are equal', () => {
    const file = tarGzFile([{ name: 'a-1.0.0/LICENSE', text: '\uFEFF\r\n  MIT License  \r\n\r\nCopyright \t\r\n\r\n\r\n' }]);
    expect(crateLicenses(crate, file).files).toEqual([{ path: 'LICENSE', text: '  MIT License\n\nCopyright' }]);
  });

  it('takes the license file that Cargo.toml names, whatever its name is', () => {
    const file = tarGzFile([
      { name: 'a-1.0.0/Cargo.toml', text: manifest('license-file = "docs/TERMS.txt"') },
      { name: 'a-1.0.0/docs/TERMS.txt', text: 'The terms' },
      { name: 'a-1.0.0/docs/OTHER.txt', text: 'Other' }
    ]);
    expect(crateLicenses(crate, file)).toEqual({ license: 'see docs/TERMS.txt', files: [{ path: 'docs/TERMS.txt', text: 'The terms' }] });
  });

  it('tells when a crate states no license and has no license file', () => {
    const file = tarGzFile([{ name: 'a-1.0.0/Cargo.toml', text: manifest('description = "license = \\"MIT\\""') }]);
    expect(crateLicenses(crate, file)).toEqual({ license: 'not stated', files: [] });
  });
});

describe('denoSourceLicenses', () => {
  it('gives the lock and the license files of the source, but not those of its tests', () => {
    const archive = tarGzFile([
      { name: 'deno/Cargo.lock', text: 'version = 4\n' },
      { name: 'deno/LICENSE.md', text: 'MIT License\n' },
      { name: 'deno/cli/tsc/dts/node/LICENSE', text: 'MIT, DefinitelyTyped\n' },
      { name: 'deno/tests/registry/npm/chalk/LICENSE', text: 'MIT, chalk\n' },
      { name: 'deno/cli/main.rs', text: 'fn main() {}' }
    ]);
    expect(denoSourceLicenses(archive)).toEqual({
      lock: 'version = 4\n',
      files: [
        { path: 'LICENSE.md', text: 'MIT License' },
        { path: 'cli/tsc/dts/node/LICENSE', text: 'MIT, DefinitelyTyped' }
      ]
    });
  });

  it('refuses a source with no lock, as nothing names the crates of the program', () => {
    const archive = tarGzFile([{ name: 'deno/LICENSE.md', text: 'MIT License\n' }, { name: 'deno/cli/Cargo.lock', text: '' }]);
    expect(() => denoSourceLicenses(archive)).toThrow(/^The Deno source of the release has no Cargo\.lock, /);
  });
});

describe('submodulesOf', () => {
  const gitmodules = `[submodule "v8"]
\tpath = v8
\turl = https://github.com/denoland/v8.git
[submodule "third_party/icu"]
\turl = https://chromium.googlesource.com/chromium/deps/icu.git
\tpath = third_party/icu
\tshallow = true
`;
  const tree = [
    { path: '.gitmodules', type: 'blob', sha: '1'.repeat(40) },
    { path: 'third_party', type: 'tree', sha: '2'.repeat(40) },
    { path: 'third_party/icu', type: 'commit', sha: 'c'.repeat(40) },
    { path: 'v8', type: 'commit', sha: 'd'.repeat(40) }
  ];

  it('gives the URL and the pinned commit of each submodule, in the order of .gitmodules', () => {
    expect(submodulesOf(gitmodules, tree)).toEqual([
      { path: 'v8', url: 'https://github.com/denoland/v8', commit: 'd'.repeat(40) },
      { path: 'third_party/icu', url: 'https://chromium.googlesource.com/chromium/deps/icu', commit: 'c'.repeat(40) }
    ]);
  });

  it('refuses a submodule with no pinned commit, and one with no URL, as its license files would be missing', () => {
    expect(() => submodulesOf(gitmodules, tree.filter(entry => entry.path !== 'v8'))).toThrow(
      /^The script cannot read a submodule of \.gitmodules \(path v8, /
    );
    const more = [...tree, { path: 'third_party/zlib', type: 'commit', sha: 'e'.repeat(40) }];
    expect(() => submodulesOf(gitmodules, more)).toThrow('.gitmodules names no URL for the submodule third_party/zlib.');
  });
});

describe('licenseTextsFile', () => {
  const rule = `${'='.repeat(80)}\n`;
  const sources = [
    { title: 'Deno 2.9.8', files: [{ path: 'LICENSE.md', text: 'The MIT text' }] },
    { title: 'crate a 1.0.0', files: [{ path: 'LICENSE-APACHE', text: 'The Apache text' }, { path: 'LICENSE-MIT', text: 'The MIT text' }] },
    { title: 'crate b 2.0.0', files: [{ path: 'LICENSE', text: 'The Apache text' }, { path: 'NOTICE', text: '' }] },
    { title: 'crate c 3.0.0', files: [] }
  ];
  const crates = [
    { name: 'a', version: '1.0.0', license: 'MIT OR Apache-2.0' },
    { name: 'b', version: '2.0.0', license: 'Apache-2.0' },
    { name: 'c', version: '3.0.0', license: 'Zlib' }
  ];
  // The parts of the file between its rule lines: the intro, then a head
  // and a text for each license text, then the head and the list of the
  // crates.
  const parts = licenseTextsFile('The intro.', sources, crates).split(rule);

  it('has each text once, at the place of its first file, with a head that names every file that has it', () => {
    expect(parts.slice(0, 5)).toEqual([
      'The intro.\n\n',
      'Deno 2.9.8: LICENSE.md\ncrate a 1.0.0: LICENSE-MIT\n',
      '\nThe MIT text\n\n',
      'crate a 1.0.0: LICENSE-APACHE\ncrate b 2.0.0: LICENSE\n',
      '\nThe Apache text\n\n'
    ]);
  });

  it('has no part for an empty file, and ends with every crate and the license that it states', () => {
    expect(parts).toHaveLength(7);
    expect(parts[6]).toBe('\na 1.0.0: MIT OR Apache-2.0\nb 2.0.0: Apache-2.0\nc 3.0.0: Zlib\n');
  });
});
