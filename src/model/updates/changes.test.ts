import { describe, expect, it } from 'vitest'
import { releaseChanges } from './changes'

// The intro that `.github/release-notes-template.md` puts before the notes.
const TEMPLATE = [
  '# Desktop builds',
  '',
  'Linux AppImage and Apple Silicon macOS DMG builds are attached to this release.',
  '',
  '## Running the macOS app',
  '',
  '```bash',
  'xattr -cr /Applications/Dez.app',
  '```',
].join('\n')

describe('release change notes', () => {
  it('reads the labels and bullets that the release-notes script writes', () => {
    const body = `${TEMPLATE}

## Changes

**NEW**

- Ability to export a conversation as a PDF file (Cmd/Ctrl+E)
- Tabs can be dragged and rearranged now

**FIXES**

- Pasting text with tabs no longer moves the cursor to the wrong place

Release notes generated by glm-5.3.
`
    expect(releaseChanges(body)).toEqual([
      { kind: 'label', text: 'NEW' },
      { kind: 'list', items: ['Ability to export a conversation as a PDF file (Cmd/Ctrl+E)', 'Tabs can be dragged and rearranged now'] },
      { kind: 'label', text: 'FIXES' },
      { kind: 'list', items: ['Pasting text with tabs no longer moves the cursor to the wrong place'] },
    ])
  })

  it('reads a body edited on github.com: CRLF, an edited credit line, and a screenshot after it', () => {
    const body = [
      TEMPLATE,
      '',
      '## Changes',
      '',
      '**ENHANCEMENT**',
      '',
      '- Better table rendering',
      '',
      'Release notes generated by glm-5.3 and edited by @taoeffect.',
      '',
      '<img width="857" height="800" alt="Screenshot" src="https://github.com/user-attachments/assets/x" />',
    ].join('\r\n')
    expect(releaseChanges(body)).toEqual([
      { kind: 'label', text: 'ENHANCEMENT' },
      { kind: 'list', items: ['Better table rendering'] },
    ])
  })

  it('leaves out screenshots and markup when the credit line was deleted', () => {
    const body = [
      '## Changes',
      '',
      '**ENHANCEMENT**',
      '',
      '- Hides very long encrypted reasoning traces behind a pill',
      '',
      '<img width="347" height="227" alt="Screenshot 2026-11-08" src="https://github.com/user-attachments/assets/2f" />',
      '![Screenshot](https://github.com/user-attachments/assets/3a)',
      '<!-- a note for the editor -->',
      '---',
      'Press <kbd>Cmd</kbd>+<kbd>S</kbd> to save; a < b > c stays as it is',
    ].join('\r\n')
    expect(releaseChanges(body)).toEqual([
      { kind: 'label', text: 'ENHANCEMENT' },
      { kind: 'list', items: ['Hides very long encrypted reasoning traces behind a pill'] },
      { kind: 'paragraph', text: 'Press Cmd+S to save; a < b > c stays as it is' },
    ])
  })

  it('gives no blocks for a body without a Changes section', () => {
    expect(releaseChanges(`${TEMPLATE}\n`)).toEqual([])
    expect(releaseChanges('')).toEqual([])
    expect(releaseChanges(null)).toEqual([])
  })

  it('stops at the next h1 or h2 and treats an h3 as a label', () => {
    const body = [
      '## Changes',
      '### Fixes ###',
      '- Fixed a crash',
      '## Known issues',
      '- Not a change',
    ].join('\n')
    expect(releaseChanges(body)).toEqual([
      { kind: 'label', text: 'Fixes' },
      { kind: 'list', items: ['Fixed a crash'] },
    ])
  })

  it('joins wrapped lines, keeps a loose list together, and splits paragraphs at blank lines', () => {
    const body = [
      '## Changes',
      '',
      'Thanks to everyone',
      'who tested this release.',
      '',
      '- First change that',
      '  wraps onto a second line',
      '',
      '* Second change, after a blank line',
      '',
      'A **bold** remark that is not a label',
    ].join('\n')
    expect(releaseChanges(body)).toEqual([
      { kind: 'paragraph', text: 'Thanks to everyone who tested this release.' },
      { kind: 'list', items: ['First change that wraps onto a second line', 'Second change, after a blank line'] },
      { kind: 'paragraph', text: 'A **bold** remark that is not a label' },
    ])
  })
})
